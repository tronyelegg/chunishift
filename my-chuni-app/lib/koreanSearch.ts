/**
 * 가타카나 문자열을 한글 음차 문자열로 변환
 */
export function convertKatakanaToHangul(text: string): string {
  let result = "";
  let i = 0;
  while (i < text.length) {
    if (i + 1 < text.length) {
      const two = text.substring(i, i + 2);
      if (KANA_TO_KOR_MAP[two]) {
        result += KANA_TO_KOR_MAP[two];
        i += 2;
        continue;
      }
    }

    const char = text[i];
    if (char === "ー") {
      i++;
      continue;
    }
    if (KANA_TO_KOR_MAP[char]) {
      result += KANA_TO_KOR_MAP[char];
    } else {
      result += char;
    }
    i++;
  }
  return result;
}

/**
 * 검색어 및 대상 텍스트 정규화
 */
export function normalizeSearchString(text: string): string {
  if (!text) return "";
  return text
    .toLowerCase()
    .replace(/[\s\-_~:!?,.()（）'"`~♬♪\/\\]/g, "");
}

/**
 * 한글 초성 추출
 */
export function getHangulChosung(text: string): string {
  const CHOSUNG = [
    "ㄱ", "ㄲ", "ㄴ", "ㄷ", "ㄸ", "ㄹ", "ㅁ", "ㅂ", "ㅃ", "ㅅ", "ㅆ",
    "ㅇ", "ㅈ", "ㅉ", "ㅊ", "ㅋ", "ㅌ", "ㅍ", "ㅎ",
  ];
  let chosung = "";
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i) - 44032;
    if (code >= 0 && code <= 11171) {
      chosung += CHOSUNG[Math.floor(code / 588)];
    } else {
      chosung += text[i];
    }
  }
  return chosung;
}

/**
 * 단일 토큰이 주어진 곡 정보(제목, 아티스트, 별명, 가타카나 음차)와 일치하는지 검사
 */
function checkSingleTokenMatch(
  song: { title: string; artist: string },
  token: string
): boolean {
  const cleanToken = normalizeSearchString(token);
  if (!cleanToken) return true;

  // 1. 원본 제목 및 아티스트
  const cleanTitle = normalizeSearchString(song.title);
  const cleanArtist = normalizeSearchString(song.artist);
  if (cleanTitle.includes(cleanToken) || cleanArtist.includes(cleanToken)) {
    return true;
  }

  // 2. 가타카나 제목 음차
  const katakanaHangul = normalizeSearchString(convertKatakanaToHangul(song.title));
  if (katakanaHangul.includes(cleanToken)) {
    return true;
  }

  // 3. 곡 별칭/한국어 번역명/음차 매칭
  const songAliases = SONG_ALIASES[song.title];
  if (songAliases) {
    for (const alias of songAliases) {
      if (normalizeSearchString(alias).includes(cleanToken)) {
        return true;
      }
      if (normalizeSearchString(getHangulChosung(alias)).includes(cleanToken)) {
        return true;
      }
    }
  }

  // 4. 작곡가(아티스트) 별칭/음차 매칭 (예: t+pazolite -> 토파조, LeaF -> 리프)
  // 원본 아티스트명 직접 매칭
  const artistAliases = ARTIST_ALIASES[song.artist];
  if (artistAliases) {
    for (const alias of artistAliases) {
      if (normalizeSearchString(alias).includes(cleanToken)) {
        return true;
      }
      if (normalizeSearchString(getHangulChosung(alias)).includes(cleanToken)) {
        return true;
      }
    }
  }

  // 복합 아티스트(예: "t+pazolite feat.xxx" 또는 "A VS B") 부분 일치 검색
  for (const [artKey, artAliases] of Object.entries(ARTIST_ALIASES)) {
    if (song.artist.includes(artKey)) {
      for (const alias of artAliases) {
        if (normalizeSearchString(alias).includes(cleanToken)) {
          return true;
        }
        if (normalizeSearchString(getHangulChosung(alias)).includes(cleanToken)) {
          return true;
        }
      }
    }
  }

  // 5. 제목 한글 초성 매칭
  const titleChosung = normalizeSearchString(getHangulChosung(song.title));
  if (titleChosung.includes(cleanToken)) {
    return true;
  }

  return false;
}

/**
 * 쿼리에서 "츄니즘", "chuni", "chunithm" 등 불필요한 접두/수식어 제거 및 정제
 */
function cleanQueryString(query: string): string {
  return query
    .replace(/(?:^|\s)(?:츄니즘|chuni|chunithm|춘|チュウニズム)(?:\s|$)/gi, " ")
    .trim();
}

/**
 * 주어진 곡이 검색 쿼리와 일치하는지 종합 검사
 * - "츄니즘 말쿠트", "츄니즘 포세이큰 테일" 같은 수식어 제거
 * - 공백으로 분리된 다중 토큰(예: "토파조 포세이큰") AND 매칭 지원
 * - 작곡가 한국어 명칭(토파조, 리프 등) & 곡명 음차/번역명 완벽 지원
 */
export function matchSongSearch(
  song: { title: string; artist: string },
  query: string
): boolean {
  if (!query || !query.trim()) return true;

  // 1. "츄니즘" 등 불필요한 수식어 제거
  const refinedQuery = cleanQueryString(query);
  const targetQuery = refinedQuery || query;

  // 2. 단어별 토큰 분리 (예: "포세이큰 테일", "토파조 포세이큰")
  const tokens = targetQuery.trim().split(/\s+/).filter(Boolean);

  // 모든 토큰이 만족되어야 함 (AND 매칭)
  for (const token of tokens) {
    if (!checkSingleTokenMatch(song, token)) {
      return false;
    }
  }

  return true;
}

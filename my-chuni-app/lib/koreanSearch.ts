/**
 * 가타카나 문자열을 한글 음차 문자열로 변환
 */
export function convertKatakanaToHangul(text: string): string {
  let result = "";
  let i = 0;
  while (i < text.length) {
    // 2글자 복합음 검사
    if (i + 1 < text.length) {
      const two = text.substring(i, i + 2);
      if (KANA_TO_KOR_MAP[two]) {
        result += KANA_TO_KOR_MAP[two];
        i += 2;
        continue;
      }
    }

    const char = text[i];
    if (char === "ー") {
      // 장음은 생략
      i++;
      continue;
    }
    if (KANA_TO_KOR_MAP[char]) {
      result += KANA_TO_KOR_MAP[char];
    } else {
      result += char;
    }
    i++;
  }
  return result;
}

/**
 * 검색어 및 대상 텍스트 정규화 (공백, 기호 제거, 소문자화)
 */
export function normalizeSearchString(text: string): string {
  if (!text) return "";
  return text
    .toLowerCase()
    .replace(/[\s\-_~:!?,.()（）'"`~♬♪]/g, "");
}

/**
 * 한글 초성 추출
 */
export function getHangulChosung(text: string): string {
  const CHOSUNG = [
    "ㄱ", "ㄲ", "ㄴ", "ㄷ", "ㄸ", "ㄹ", "ㅁ", "ㅂ", "ㅃ", "ㅅ", "ㅆ",
    "ㅇ", "ㅈ", "ㅉ", "ㅊ", "ㅋ", "ㅌ", "ㅍ", "ㅎ"
  ];
  let chosung = "";
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i) - 44032;
    if (code >= 0 && code <= 11171) {
      chosung += CHOSUNG[Math.floor(code / 588)];
    } else {
      chosung += text[i];
    }
  }
  return chosung;
}

/**
 * 주어진 곡이 검색 쿼리와 일치하는지 종합 검사
 * - 원본 제목, 아티스트
 * - 한국어 사전 매핑 (번역명, 약칭, 별칭)
 * - 가타카나 한글 음차 변환
 * - 초성 검색
 */
export function matchSongSearch(
  song: { title: string; artist: string },
  query: string
): boolean {
  const cleanQuery = normalizeSearchString(query);
  if (!cleanQuery) return true;

  // 1. 원본 제목 및 아티스트 검색
  const cleanTitle = normalizeSearchString(song.title);
  const cleanArtist = normalizeSearchString(song.artist);

  if (cleanTitle.includes(cleanQuery) || cleanArtist.includes(cleanQuery)) {
    return true;
  }

  // 2. 가타카나 -> 한글 변환 매칭
  const katakanaHangul = normalizeSearchString(convertKatakanaToHangul(song.title));
  if (katakanaHangul.includes(cleanQuery)) {
    return true;
  }

  // 3. 한국어 사전(별칭/번역명/음차) 매칭
  const aliases = SONG_ALIASES[song.title];
  if (aliases && aliases.length > 0) {
    for (const alias of aliases) {
      const cleanAlias = normalizeSearchString(alias);
      if (cleanAlias.includes(cleanQuery)) {
        return true;
      }
      // 초성 매칭
      const aliasChosung = normalizeSearchString(getHangulChosung(alias));
      if (aliasChosung.includes(cleanQuery)) {
        return true;
      }
    }
  }

  // 4. 제목 한글 초성 매칭
  const titleChosung = normalizeSearchString(getHangulChosung(song.title));
  if (titleChosung.includes(cleanQuery)) {
    return true;
  }

  return false;
}
